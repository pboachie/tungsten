//! Package files: the gemspec, the Gemfile, the RuboCop configuration and
//! the README.

use tungsten_emit::Writer;
use tungsten_emit::sdk::MemberKind;
use tungsten_ir::Safety;

use crate::context::Gen;
use crate::rb::{comment, one_line, str_lit};

/// Every package file.
pub fn files(g: &Gen<'_, '_>) -> Vec<(String, String)> {
    vec![
        (format!("{}.gemspec", g.opts.gem), gemspec(g)),
        ("Gemfile".to_string(), gemfile(g)),
        (".rubocop.yml".to_string(), rubocop(g)),
        ("README.md".to_string(), readme(g)),
    ]
}

fn title(g: &Gen<'_, '_>) -> String {
    let api = &g.plan.ir.api;
    if api.title.trim().is_empty() {
        api.name.wire.clone()
    } else {
        api.title.trim().to_string()
    }
}

fn gemspec(g: &Gen<'_, '_>) -> String {
    let mut w = Writer::new("  ");
    g.file_start(&mut w);
    w.block("Gem::Specification.new do |spec|", "end", |w| {
        w.line(format!("spec.name = {}", str_lit(&g.opts.gem)));
        w.line(format!("spec.version = {}", str_lit(&g.opts.version)));
        w.line("spec.authors = [\"tungsten\"]");
        w.line(format!(
            "spec.summary = {}",
            str_lit(&format!("Ruby SDK for {}", title(g)))
        ));
        if let Some(d) = g
            .plan
            .ir
            .api
            .description
            .as_deref()
            .map(one_line)
            .filter(|d| !d.is_empty())
        {
            w.line(format!("spec.description = {}", str_lit(&d)));
        }
        w.line("spec.files = Dir[\"lib/**/*.rb\", \"lib/**/*.json\", \"README.md\"]");
        w.line("spec.require_paths = [\"lib\"]");
        w.line("spec.required_ruby_version = \">= 3.3\"");
        w.line(format!(
            "spec.add_dependency \"tungsten-runtime\", {}",
            str_lit(&g.opts.runtime)
        ));
        w.line("spec.metadata[\"rubygems_mfa_required\"] = \"true\"");
    });
    w.finish()
}

fn gemfile(g: &Gen<'_, '_>) -> String {
    let mut w = Writer::new("  ");
    g.file_start(&mut w);
    w.line("source \"https://rubygems.org\"");
    w.blank();
    w.line("gemspec");
    if let Some(path) = &g.opts.runtime_path {
        w.blank();
        w.line(format!("gem \"tungsten-runtime\", path: {}", str_lit(path)));
    }
    w.finish()
}

fn rubocop(g: &Gen<'_, '_>) -> String {
    let mut w = Writer::new("  ");
    w.line(&g.header);
    comment(
        &mut w,
        "The checks generated files pass: the Lint department and the frozen string\nliteral comment. Layout and style are the generator's.",
    );
    w.line("AllCops:");
    w.indent();
    w.line("TargetRubyVersion: 3.3");
    w.line("DisabledByDefault: true");
    w.line("NewCops: disable");
    w.line("SuggestExtensions: false");
    w.dedent();
    w.line("Lint:");
    w.indent();
    w.line("Enabled: true");
    w.dedent();
    w.line("Style/FrozenStringLiteralComment:");
    w.indent();
    w.line("Enabled: true");
    w.line("EnforcedStyle: always");
    w.dedent();
    w.finish()
}

fn readme(g: &Gen<'_, '_>) -> String {
    let mut out = String::new();
    let t = title(g);
    let m = g.module();
    let client = &g.names.client_class;
    let lib = g.lib();
    out.push_str(&format!("# {}\n\n", g.opts.gem));
    out.push_str(&format!(
        "<!-- {} -->\n\n",
        g.header.replace("# ", "").replace('\n', " ")
    ));
    out.push_str(&format!(
        "Ruby SDK for {t}, generated by tungsten. It needs Ruby 3.3 or later and the `tungsten-runtime` gem ({}); the runtime uses the standard library only (`net/http`, `json`, `openssl`).\n\n",
        g.opts.runtime
    ));
    if let Some(d) = g
        .plan
        .ir
        .api
        .description
        .as_deref()
        .map(str::trim)
        .filter(|d| !d.is_empty())
    {
        out.push_str(&one_line(d));
        out.push_str("\n\n");
    }
    out.push_str("## Usage\n\n```ruby\n");
    out.push_str(&format!("require \"{lib}\"\n\n"));
    out.push_str(&format!(
        "client = {m}::{client}.new(base_url: \"https://api.example.com\", auth: {{ ... }})\n"
    ));
    if let Some(first) = g.plan.operations.iter().enumerate().find(|(_, o)| {
        o.arguments
            .iter()
            .all(|a| !matches!(a.presence, tungsten_ir::Presence::Required))
    }) {
        let (o, op) = first;
        let chain = g.resource_chain(op.resource).join(".");
        if let Some(member) = g.member(op.resource, MemberKind::Operation(o)) {
            out.push_str(&format!("result = client.{chain}.{member}\n"));
        }
    }
    out.push_str(
        "if result.ok?\n  puts result.value\nelse\n  warn result.error.remediation\nend\n```\n\n",
    );
    out.push_str(
        "Every method returns `Tungsten::Runtime::Ok` (`value`, `raw`, `meta`, `verification`) or `Tungsten::Runtime::Err` (`error`: the diagnostic envelope with `category`, `remediation`, `retryable`, `next_action`, ...; `partial`: what a failed call already produced). API and transport failures never raise.\n\n",
    );
    out.push_str(
        "Arguments are keywords with the Ruby names (snake_case); call options go in `opts:`:\n\n",
    );
    out.push_str("```ruby\nclient.some_resource.create(name: \"x\", opts: { idempotency_key: SecureRandom.uuid, timeout_ms: 10_000 })\n```\n\n");
    out.push_str("- `idempotency_key`: the key of an operation that takes one (generate it once per intent and reuse it on every retry);\n");
    out.push_str("- `confirm`: `true` for a destructive operation, or the `confirmation_token` of the operation's `preview_<method>` (the only way for an irreversible one);\n");
    out.push_str("- `timeout_ms`, `verify`, `headers`.\n\n");
    out.push_str("Client options (keywords of `new`): `base_url`, `auth` (credentials by scheme name), `timeout_ms`, `retries`, `idempotency_store`, `middleware`, `validate_responses` (`\"warn\"`, `\"strict\"`, `\"off\"`), `on_diagnostic`, `headers`, `max_event_bytes`, `max_reconnects`, `reconnect_max_ms`, `idle_timeout_ms`, `token_store`.\n\n");
    let mut destructive: Vec<String> = vec![];
    for (o, op) in g.plan.operations.iter().enumerate() {
        if matches!(op.safety, Safety::Destructive | Safety::Irreversible)
            && let Some(member) = g.member(op.resource, MemberKind::Operation(o))
        {
            let chain = g.resource_chain(op.resource).join(".");
            destructive.push(format!("`client.{chain}.{member}` (`{}`)", op.op.id.0));
        }
    }
    if !destructive.is_empty() {
        out.push_str("## Confirmation\n\n");
        out.push_str("These operations need `confirm`: ");
        out.push_str(&destructive.join(", "));
        out.push_str(".\n\n");
    }
    out.push_str("## Operations\n\n| Method | Operation | Safety |\n|---|---|---|\n");
    for (o, op) in g.plan.operations.iter().enumerate() {
        let chain = g.resource_chain(op.resource).join(".");
        let member = g
            .member(op.resource, MemberKind::Operation(o))
            .unwrap_or("");
        out.push_str(&format!(
            "| `client.{chain}.{member}` | `{}` | `{}` |\n",
            op.op.id.0,
            tungsten_emit::sdk::descriptors::safety_str(op.safety)
        ));
    }
    out.push('\n');
    if !g.plan.macros.is_empty() {
        out.push_str("## Macros\n\n| Method | Macro |\n|---|---|\n");
        for (i, mac) in g.plan.macros.iter().enumerate() {
            out.push_str(&format!(
                "| `client.macros.{}` | `{}` |\n",
                g.names.macros[i].member,
                mac.name()
            ));
        }
        out.push('\n');
    }
    out.push_str(&format!(
        "## Custom code\n\n`lib/{lib}/custom/extensions.rb` is yours: tungsten creates it once and never overwrites it, and the gem requires it last.\n"
    ));
    out
}
