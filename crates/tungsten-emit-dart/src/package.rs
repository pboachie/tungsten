/// Every package file; `libraries` are the generated libraries the entry
/// library exports.
pub(crate) fn files(g: &Gen<'_, '_>, libraries: &[Library]) -> Vec<(String, String)> {
    vec![
        ("pubspec.yaml".to_string(), pubspec(g)),
        ("analysis_options.yaml".to_string(), analysis_options(g)),
        ("README.md".to_string(), readme(g)),
        (format!("lib/{}.dart", g.opts.package), entry(g, libraries)),
        (format!("lib/{CUSTOM}"), custom()),
    ]
}

fn title(g: &Gen<'_, '_>) -> String {
    let api = &g.plan.ir.api;
    if api.title.trim().is_empty() {
        api.name.wire.clone()
    } else {
        one_line(api.title.trim())
    }
}

/// A double-quoted YAML scalar of `text`.
fn yaml_str(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\x{:02x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn hash_header(g: &Gen<'_, '_>) -> String {
    g.header
        .lines()
        .map(|l| format!("#{}", l.trim_start_matches("//")))
        .collect::<Vec<_>>()
        .join("\n")
}

fn pubspec(g: &Gen<'_, '_>) -> String {
    let mut out = hash_header(g);
    out.push('\n');
    out.push_str(&format!("name: {}\n", g.opts.package));
    out.push_str(&format!(
        "description: {}\n",
        yaml_str(&format!(
            "Dart SDK for {}, generated by tungsten over tungsten_runtime.",
            title(g)
        ))
    ));
    out.push_str(&format!("version: {}\n", g.opts.version));
    if g.opts.runtime_path.is_some() {
        // A path dependency cannot be published.
        out.push_str("publish_to: none\n");
    }
    out.push_str("\nenvironment:\n  sdk: \">=3.6.0 <4.0.0\"\n\n");
    out.push_str("dependencies:\n");
    match &g.opts.runtime_path {
        Some(path) => out.push_str(&format!(
            "  {RUNTIME_PACKAGE}:\n    path: {}\n",
            yaml_str(path)
        )),
        None => out.push_str(&format!(
            "  {RUNTIME_PACKAGE}: {}\n",
            yaml_str(&g.opts.runtime)
        )),
    }
    out
}

fn analysis_options(g: &Gen<'_, '_>) -> String {
    let mut out = hash_header(g);
    out.push('\n');
    out.push_str(
        "# The checks generated code passes: dart analyze --fatal-infos with these\n# options, and dart format.\n",
    );
    out.push_str("analyzer:\n  language:\n    strict-casts: true\n    strict-inference: true\n    strict-raw-types: true\n\n");
    out.push_str("linter:\n  rules:\n");
    for l in LINTS {
        out.push_str(&format!("    - {l}\n"));
    }
    out
}

/// The entry library: every generated library, each name exported once
/// (from the first library that declares it), then the custom library.
fn entry(g: &Gen<'_, '_>, libraries: &[Library]) -> String {
    let mut out = String::new();
    out.push_str(&g.header);
    out.push_str("\n\n");
    out.push_str(&format!(
        "/// Dart SDK for {}, generated by tungsten.\n",
        title(g)
    ));
    out.push_str("///\n");
    out.push_str(&format!(
        "/// Runs over `package:{RUNTIME_PACKAGE}`; see the package README.\n"
    ));
    out.push_str("library;\n\n");
    let mut seen: BTreeSet<String> = BTreeSet::new();
    for lib in libraries {
        let Some(names) = &lib.exports else {
            continue;
        };
        let hidden: Vec<String> = names
            .iter()
            .filter(|n| seen.contains(n.as_str()))
            .cloned()
            .collect();
        seen.extend(names.iter().cloned());
        out.push_str(&directive("export", &lib.path, "hide", &hidden));
        out.push('\n');
    }
    out.push_str(&directive("export", CUSTOM, "", &[]));
    out.push('\n');
    out
}

fn custom() -> String {
    [
        "// Your code: tungsten creates this file once and never overwrites or",
        "// removes it. The package's entry library exports it, so public",
        "// declarations here (extensions on the models or the client, helpers)",
        "// are part of the package.",
        "",
    ]
    .join("\n")
}

fn readme(g: &Gen<'_, '_>) -> String {
    let mut out = String::new();
    let t = title(g);
    let p = &g.opts.package;
    let client = &g.names.client_class;
    let code_scheme = g
        .plan
        .ir
        .auth
        .iter()
        .find(|scheme| scheme.authorization_code().is_some());
    out.push_str(&format!("# {p}\n\n"));
    out.push_str(&format!(
        "<!-- {} -->\n\n",
        g.header.replace("// ", "").replace('\n', " ")
    ));
    out.push_str(&format!(
        "Dart SDK for {t}, generated by tungsten. It needs Dart 3.6 or later and the `{RUNTIME_PACKAGE}` package ({}), which runs on `dart:io` (servers, command-line tools, Flutter on mobile and desktop; not the web).\n\n",
        match &g.opts.runtime_path {
            Some(path) => format!("from `{path}`"),
            None => g.opts.runtime.clone(),
        }
    ));
    if let Some(d) = g
        .plan
        .ir
        .api
        .description
        .as_deref()
        .map(str::trim)
        .filter(|d| !d.is_empty())
    {
        out.push_str(&one_line(d));
        out.push_str("\n\n");
    }
    out.push_str("## Usage\n\n```dart\n");
    if code_scheme.is_some() {
        out.push_str("import 'dart:io';\n");
    }
    out.push_str(&format!("import 'package:{p}/{p}.dart';\n"));
    out.push_str(&format!(
        "import 'package:{RUNTIME_PACKAGE}/{RUNTIME_PACKAGE}.dart';\n\n"
    ));
    out.push_str("Future<void> main() async {\n");
    if let Some(scheme) = code_scheme {
        out.push_str(&format!(
            "  final client = {client}(ClientOptions(\n    baseUrl: 'https://api.example.com',\n    auth: {{{}: Credential.authorizationCode(\n      clientId: Platform.environment['OAUTH_CLIENT_ID'] ?? '',\n      redirectUri: Platform.environment['OAUTH_REDIRECT_URI'] ?? '',\n    )}},\n  ));\n  // Complete managed authorization below before authenticated calls.\n",
            str_lit(scheme.name())
        ));
    } else {
        out.push_str(&format!(
            "  final client = {client}(ClientOptions(baseUrl: 'https://api.example.com'));\n"
        ));
    }
    if let Some((o, op)) = g.plan.operations.iter().enumerate().find(|(_, o)| {
        o.arguments
            .iter()
            .all(|a| !matches!(a.presence, tungsten_ir::Presence::Required))
    }) && code_scheme.is_none()
        && let Some(member) = member(g, op.resource, MemberKind::Operation(o))
    {
        let chain = resource_chain(g, op.resource).join(".");
        let chain = if chain.is_empty() {
            String::new()
        } else {
            format!("{chain}.")
        };
        out.push_str(&format!(
            "  final result = await client.{chain}{member}();\n"
        ));
        out.push_str("  switch (result) {\n    case Ok(:final value):\n      print(value);\n    case Err(:final error):\n      print(error.remediation);\n  }\n");
    }
    out.push_str("}\n```\n\n");
    if let Some(scheme) = code_scheme {
        out.push_str(&format!(
            "## Managed OAuth authorization\n\nSet `OAUTH_CLIENT_ID` and `OAUTH_REDIRECT_URI` to the registered client and exact redirect before constructing the client. Public clients omit `clientSecret`; confidential clients supply it from application-owned secure configuration. Qualify S256 support and issuer-response behavior before enabling the provider. The application supplies `sessionBinding` from its owning listener/browser session, the exact qualified `issuer`, and the full `callbackUrl` delivered to that same owner.\n\n```dart\nfinal flow = client.oauth({});\ntry {{\n  final begun = flow.authorizationUrl(\n    sessionBinding: sessionBinding,\n    issuerDefense: IssuerDefense.issuerResponse(issuer),\n    s256Supported: true,\n  );\n  if (begun is Err<AuthorizationAttempt>) {{\n    throw StateError(begun.error.remediation);\n  }}\n  final attempt = (begun as Ok<AuthorizationAttempt>).value;\n  // Open attempt.url in the owning browser and await its full callbackUrl.\n  final completed = await flow.exchangeCode(\n    attemptHandle: attempt.attemptHandle,\n    callbackUrl: callbackUrl,\n    sessionBinding: sessionBinding,\n  );\n  if (completed is Err<TokenInfo>) {{\n    throw StateError(completed.error.remediation);\n  }}\n  // Authenticated generated methods may now be called.\n}} finally {{\n  flow.cancelAllAuthorization();\n}}\n```\n\n`cancelAllAuthorization()` synchronously invalidates pending attempts and running token work and disposes attempt timers. Owned network/store work retains admission until settlement; an already stored credential is preserved and a new attempt may begin. Call `await flow.logout()` separately to invalidate and remove local credentials; neither operation remotely revokes tokens. Custom managed stores require `FencedTokenStore` final atomic predicates. Keep handles, authorization/callback URLs, session bindings, codes and tokens out of logs. Shared persistent adapters and actual provider/listener behavior need separate qualification. The deliberately unbound `lowLevelAuthorizationUrl` and `lowLevelExchangeCode` are compatibility primitives, never the managed default.\n\n",
            str_lit(scheme.name())
        ));
    }
    out.push_str(
        "Every method returns a `Future<Result<T>>`: `Ok` (`value`, `raw`, `meta`, `verification`) or `Err` (`error`: the diagnostic envelope with `category`, `remediation`, `retryable`, `nextAction`, ...). API and transport failures never throw.\n\n",
    );
    out.push_str("Models are final classes with `fromJson` and `toJson`. A required member is `T`, a required member that may be null `T?`, an optional member `T?` (null is not sent), and an optional member that may be null a `Patch<T>`: `Patch.absent()`, `Patch.nullValue()` or `Patch.of(value)`. Bytes are `Uint8List`.\n\n");
    out.push_str("Call options (`CallOptions`): `idempotencyKey` (generate it once per intent and reuse it on every retry), `confirm` (`Confirm.yes` for a destructive operation, or the confirmation token of its preview, the only way for an irreversible one), `timeout`.\n\n");
    let mut destructive: Vec<String> = vec![];
    for op in &g.plan.operations {
        if matches!(op.safety, Safety::Destructive | Safety::Irreversible) {
            destructive.push(format!("`{}`", op.op.id.0));
        }
    }
    if !destructive.is_empty() {
        out.push_str("## Confirmation\n\n");
        out.push_str("These operations need `confirm`: ");
        out.push_str(&destructive.join(", "));
        out.push_str(".\n\n");
    }
    out.push_str("## Operations\n\n| Method | Operation | Safety |\n|---|---|---|\n");
    for (o, op) in g.plan.operations.iter().enumerate() {
        let mut path = resource_chain(g, op.resource);
        path.push(
            member(g, op.resource, MemberKind::Operation(o))
                .unwrap_or("")
                .to_string(),
        );
        out.push_str(&format!(
            "| `client.{}` | `{}` | `{}` |\n",
            path.join("."),
            op.op.id.0,
            tungsten_emit::sdk::descriptors::safety_str(op.safety)
        ));
    }
    out.push('\n');
    if !g.plan.macros.is_empty() {
        out.push_str("## Macros\n\n| Method | Macro |\n|---|---|\n");
        for (i, mac) in g.plan.macros.iter().enumerate() {
            out.push_str(&format!(
                "| `client.macros.{}` | `{}` |\n",
                g.names.macros[i].member,
                mac.name()
            ));
        }
        out.push('\n');
    }
    out.push_str(&format!(
        "## Custom code\n\n`lib/{CUSTOM}` is yours: tungsten creates it once and never overwrites it, and `lib/{p}.dart` exports it.\n"
    ));
    out
}

/// The name of a member of a resource.
fn member<'g>(g: &'g Gen<'_, '_>, resource: usize, kind: MemberKind) -> Option<&'g str> {
    g.names.resources[resource]
        .members
        .iter()
        .find(|m| m.kind == kind)
        .map(|m| m.name.as_str())
}

/// The getter chain from a client to a resource (`public.webhooks`).
fn resource_chain(g: &Gen<'_, '_>, resource: usize) -> Vec<String> {
    use tungsten_emit::sdk::ClientPlan;
    let mut chain: Vec<String> = vec![];
    let mut cur = resource;
    loop {
        match g.plan.resources[cur].parent {
            Some(p) => {
                chain.push(
                    member(g, p, MemberKind::Child(cur))
                        .unwrap_or_default()
                        .to_string(),
                );
                cur = p;
            }
            None => {
                match &g.plan.client {
                    ClientPlan::Resources(list) => {
                        if let Some(i) = list.iter().position(|&r| r == cur) {
                            chain.push(g.names.client_members[i].clone());
                        }
                    }
                    ClientPlan::Namespaces(list) => {
                        for (n, ns) in list.iter().enumerate() {
                            if let Some(i) = ns.resources.iter().position(|&r| r == cur) {
                                chain.push(g.names.namespace_members[n][i].clone());
                                chain.push(g.names.client_members[n].clone());
                            }
                        }
                    }
                }
                break;
            }
        }
    }
    chain.reverse();
    chain
}
