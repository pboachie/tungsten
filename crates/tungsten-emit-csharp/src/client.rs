impl Ctx<'_> {
    /// The expression of each resource from the client, by resource index.
    fn resource_paths(&self) -> Vec<String> {
        let mut paths = vec![String::new(); self.plan.resources.len()];
        match &self.plan.client {
            ClientPlan::Resources(top) => {
                for (r, m) in top.iter().zip(&self.names.client_members) {
                    paths[*r] = m.clone();
                }
            }
            ClientPlan::Namespaces(namespaces) => {
                for (k, ns) in namespaces.iter().enumerate() {
                    let member = &self.names.client_members[k];
                    for (r, m) in ns.resources.iter().zip(&self.names.namespace_members[k]) {
                        paths[*r] = format!("{member}.{m}");
                    }
                }
            }
        }
        // Resources come depth first: every parent before its children.
        for (r, names) in self.names.resources.iter().enumerate() {
            for m in &names.members {
                if let MemberKind::Child(c) = m.kind {
                    paths[c] = format!("{}.{}", paths[r], m.name);
                }
            }
        }
        paths
    }

    /// The macros class name: `<Client>Macros`, unique among the classes.
    fn macros_class(&self) -> String {
        let mut taken: Vec<String> = self
            .names
            .resources
            .iter()
            .map(|r| r.class.clone())
            .collect();
        taken.extend(self.names.namespace_classes.iter().cloned());
        taken.push(self.names.client_class.clone());
        cs::unique(format!("{}Macros", self.names.client_class), &mut taken)
    }

    fn has_code_flow(&self) -> bool {
        self.ir
            .auth
            .iter()
            .any(|s| matches!(s, AuthScheme::OAuth2 { .. }) && s.authorization_code().is_some())
    }

    /// `<PackageId>.csproj`.
    pub fn csproj(&self) -> String {
        let header = header_text(self.ir).replace("--", "- -");
        let reference = match &self.opts.runtime_path {
            Some(path) => format!(
                "    <ProjectReference Include=\"{}/Tungsten.Runtime.csproj\" />",
                path.trim_end_matches('/')
            ),
            None => format!(
                "    <PackageReference Include=\"Tungsten.Runtime\" Version=\"{}\" />",
                self.opts.runtime
            ),
        };
        let mut out = String::new();
        for line in header.lines() {
            out.push_str(&format!("<!-- {line} -->\n"));
        }
        out.push_str(&format!(
            r#"<Project Sdk="Microsoft.NET.Sdk">

  <PropertyGroup>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
    <IsTrimmable>true</IsTrimmable>
    <IsAotCompatible>true</IsAotCompatible>
    <RootNamespace>{ns}</RootNamespace>
    <AssemblyName>{pkg}</AssemblyName>
    <PackageId>{pkg}</PackageId>
    <Version>{version}</Version>
  </PropertyGroup>

  <ItemGroup>
    <EmbeddedResource Include="tungsten-descriptors.json" LogicalName="tungsten-descriptors.json" />
  </ItemGroup>

  <ItemGroup>
{reference}
  </ItemGroup>

</Project>
"#,
            ns = self.opts.namespace,
            pkg = self.opts.package_id,
            version = self.opts.version,
        ));
        out
    }

    /// `README.md`.
    pub fn readme(&self) -> String {
        let client = &self.names.client_class;
        let title = &self.ir.api.title;
        let mut out = format!(
            "# {pkg}\n\nThe C# SDK of the {title} API, generated by tungsten {v}. Do not edit the generated files; \
             put your own code in `custom/`.\n\n## Install\n\n```sh\ndotnet add package {pkg} --version {version}\n```\n\n\
             It depends on `Tungsten.Runtime` (net10.0), which carries validation, auth, idempotency, \
             confirmation, retries, pagination, streams and the error envelope.\n\n## Use\n\n```csharp\n\
             using {ns};\nusing Tungsten.Runtime;\n\nvar client = new {client}(new ClientOptions\n{{\n    \
             BaseUrl = \"https://api.example.com\",\n}});\n```\n\nEvery operation is an async method returning \
             `Result<T>`: `Result<T>.Ok` with the typed value, or `Result<T>.Err` with the diagnostic \
             envelope (category, remediation, retryable). Destructive operations need a confirmation \
             token from their `Preview...Async` method, passed as `new CallOptions {{ Confirm = \
             Confirm.Token(token) }}`.\n",
            pkg = self.opts.package_id,
            ns = self.opts.namespace,
            v = self.ir.generator.tungsten_version,
            version = self.opts.version,
        );
        if !self.plan.operations.is_empty() {
            out.push_str("\n## Operations\n\n| Operation | Method |\n|---|---|\n");
            let paths = self.resource_paths();
            for (i, p) in self.plan.operations.iter().enumerate() {
                let member = self.names.resources[p.resource]
                    .members
                    .iter()
                    .find(|m| m.kind == MemberKind::Operation(i))
                    .map(|m| m.name.clone())
                    .unwrap_or_default();
                out.push_str(&format!(
                    "| `{}` | `{}.{member}Async` |\n",
                    p.op.id.0, paths[p.resource]
                ));
            }
        }
        out
    }

    /// `custom/README.md`.
    pub fn custom_readme(&self) -> String {
        format!(
            "# custom\n\nFiles in this directory are yours: tungsten creates this one once and never \
             overwrites or removes anything here. The project compiles every `.cs` file in it, so \
             helpers can extend the generated client, for example with `public sealed partial class \
             {} {{ ... }}` in the `{}` namespace.\n",
            self.names.client_class, self.opts.namespace
        )
    }

    /// `Client.cs`.
    pub fn client_file(&self) -> String {
        let client = &self.names.client_class;
        let mut w = self.file_writer();
        Self::root_usings(&mut w);
        w.line(format!("namespace {};", self.opts.namespace));
        w.blank();
        cs::summary_line(
            &mut w,
            &format!("The client of the {} API.", self.ir.api.title),
        );
        w.line(format!("public sealed partial class {client}"));
        w.line("{");
        w.indent();
        let members: Vec<(String, String)> = match &self.plan.client {
            ClientPlan::Resources(top) => top
                .iter()
                .zip(&self.names.client_members)
                .map(|(r, m)| (m.clone(), self.names.resources[*r].class.clone()))
                .collect(),
            ClientPlan::Namespaces(_) => self
                .names
                .client_members
                .iter()
                .zip(&self.names.namespace_classes)
                .map(|(m, c)| (m.clone(), c.clone()))
                .collect(),
        };
        let macros = !self.plan.macros.is_empty();
        let macros_class = self.macros_class();
        cs::summary_line(
            &mut w,
            "A client; throws ClientConfigException when the options are invalid (a base URL that is not an absolute http(s) URL).",
        );
        w.line(format!("public {client}(ClientOptions? options = null)"));
        w.line("{");
        w.indent();
        if self.ir.agent.redirects == tungsten_ir::RedirectPolicy::None {
            w.line("ClientCore.RequireRedirectPolicyV1();");
        }
        if self
            .plan
            .operations
            .iter()
            .any(|p| p.op.agent.import_policy.is_some())
        {
            w.line("ClientCore.RequireImportPolicyV1();");
        }
        w.line("Core = new ClientCore(Ops.Document, options);");
        for (m, class) in &members {
            w.line(format!("{m} = new {class}(Core);"));
        }
        if macros {
            w.line(format!("Macros = new {macros_class}(Core);"));
        }
        w.dedent();
        w.line("}");
        w.blank();
        cs::summary_line(&mut w, "The runtime engine every method calls through.");
        w.line("public ClientCore Core { get; }");
        for (m, class) in &members {
            w.blank();
            w.line(format!("public {class} {m} {{ get; }}"));
        }
        if macros {
            w.blank();
            cs::summary_line(&mut w, "The macros of the API: several calls as one step.");
            w.line(format!("public {macros_class} Macros {{ get; }}"));
        }
        if self.has_code_flow() {
            w.blank();
            cs::summary_line(
                &mut w,
                "Managed OAuth2 attempts, full-callback validation, refresh and local logout for a scheme.",
            );
            w.line("public OAuthFlow OAuth(string scheme) => Core.OAuth(scheme);");
        }
        w.dedent();
        w.line("}");
        w.finish()
    }

    /// The fields of a macro's input record.
    fn macro_fields(&self, k: usize, record: &str) -> Vec<ArgField> {
        let m = &self.plan.macros[k];
        let base = m.base.map(|b| &self.plan.operations[b]);
        let words: Vec<Vec<String>> = m.input.iter().map(|f| f.words.clone()).collect();
        let props = Self::arg_props(&words, record);
        m.input
            .iter()
            .zip(props)
            .map(|(f, prop)| {
                let ct = match (&f.source, base) {
                    (InputSource::Argument(i), Some(op)) => op
                        .arguments
                        .get(*i)
                        .and_then(|a| a.ty.as_ref())
                        .map_or_else(Ct::any, |t| self.ct(t, None)),
                    _ => Ct::any(),
                };
                ArgField {
                    prop,
                    key: f.key.clone(),
                    ct,
                    presence: f.presence,
                    doc: String::new(),
                }
            })
            .collect()
    }

    /// `Macros.cs`.
    pub fn macros_file(&self) -> String {
        let mut w = self.file_writer();
        Self::root_usings(&mut w);
        w.line(format!("namespace {};", self.opts.namespace));
        w.blank();
        let class = self.macros_class();
        cs::summary_line(
            &mut w,
            "The macros of the API: several calls as one step, with previews and confirmation.",
        );
        w.line(format!("public sealed class {class}"));
        w.line("{");
        w.indent();
        w.line("private readonly ClientCore core;");
        w.blank();
        w.line(format!("internal {class}(ClientCore core)"));
        w.line("{");
        w.line("    this.core = core;");
        w.line("}");
        for (k, m) in self.plan.macros.iter().enumerate() {
            let member = &self.names.macros[k].member;
            let record = format!("{member}Input");
            let fields = self.macro_fields(k, &record);
            w.blank();
            self.args_record(
                &mut w,
                &record,
                &format!("The input of {}.", m.name()),
                &fields,
            );
            let optional = fields.iter().all(|f| {
                matches!(
                    f.presence,
                    tungsten_ir::Presence::Optional | tungsten_ir::Presence::OptionalNullable
                )
            });
            let (param, args) = if optional {
                (
                    format!("{record}? input = null"),
                    format!("(input ?? new {record}()).ToJson()"),
                )
            } else {
                (format!("{record} input"), "input.ToJson()".to_string())
            };
            let tail = "CallOptions? options = null, CancellationToken cancellationToken = default";
            let summary = m.source.summary.trim();
            w.blank();
            cs::summary_line(
                &mut w,
                if summary.is_empty() {
                    "Runs the macro."
                } else {
                    summary
                },
            );
            w.line(format!(
                "public Task<Result<JsonNode?>> {member}Async({param}, {tail}) =>"
            ));
            w.line(format!(
                "    core.RunMacroAsync(Ops.Macro{member}, {args}, options, cancellationToken);"
            ));
            w.blank();
            cs::summary_line(
                &mut w,
                "Renders every step of the macro without sending anything, with a confirmation token for this input.",
            );
            w.line(format!(
                "public Task<Result<PreviewResult>> Preview{member}Async({param}, {tail}) =>"
            ));
            w.line(format!(
                "    core.PreviewMacroAsync(Ops.Macro{member}, {args}, options, cancellationToken);"
            ));
        }
        w.dedent();
        w.line("}");
        w.finish()
    }

    /// `Dispatch.cs`.
    pub fn dispatch_file(&self, infos: &[OpInfo]) -> String {
        let client = &self.names.client_class;
        let paths = self.resource_paths();
        let mut w = self.file_writer();
        w.line("using System.Collections.Generic;");
        w.line("using System.Linq;");
        w.line("using System.Text.Json.Nodes;");
        w.line("using System.Threading;");
        w.line("using System.Threading.Tasks;");
        w.line("using Tungsten.Runtime;");
        w.blank();
        w.line(format!("namespace {};", self.opts.namespace));
        w.blank();
        cs::summary_line(
            &mut w,
            "Operations by id and macros by name with JSON arguments, through the typed methods (the runtime's IDispatch).",
        );
        w.line(format!("public sealed partial class {client} : IDispatch"));
        w.line("{");
        w.indent();
        let ops = infos
            .iter()
            .map(|i| format!("Ops.{}", i.field))
            .collect::<Vec<_>>()
            .join(", ");
        w.line(format!(
            "private static readonly OperationDescriptor[] DispatchOperations = {};",
            array_literal(&ops)
        ));
        let macros = self
            .names
            .macros
            .iter()
            .map(|m| format!("Ops.Macro{}", m.member))
            .collect::<Vec<_>>()
            .join(", ");
        w.line(format!(
            "private static readonly MacroDescriptor[] DispatchMacros = {};",
            array_literal(&macros)
        ));
        w.blank();
        w.line("ClientCore IDispatch.Core => Core;");
        w.blank();
        w.line("IReadOnlyList<OperationDescriptor> IDispatch.Operations => DispatchOperations;");
        w.blank();
        w.line("IReadOnlyList<MacroDescriptor> IDispatch.Macros => DispatchMacros;");
        let request_type = |p: usize, info: &OpInfo| -> String {
            format!("{}.{}", self.names.resources[p].class, info.request)
        };
        let decode = |w: &mut tungsten_emit::Writer, ty: &str| {
            w.line(format!(
                "if (!Typed.TryDecodeArgs<{ty}>(args, {ty}.FromJson, out var request))"
            ));
        };
        // InvokeAsync
        w.blank();
        if self.plan.operations.is_empty() {
            w.line("Task<Result<JsonNode?>> IDispatch.InvokeAsync(string operation, JsonObject args, CallOptions? options, CancellationToken cancellationToken) =>");
            w.line("    Task.FromResult(Typed.UnknownOperation<JsonNode?>(operation));");
            w.blank();
            w.line("Task<Result<PreviewResult>> IDispatch.PreviewOperationAsync(string operation, JsonObject args, CallOptions? options, CancellationToken cancellationToken) =>");
            w.line("    Task.FromResult(Typed.UnknownOperation<PreviewResult>(operation));");
        } else {
            w.line("async Task<Result<JsonNode?>> IDispatch.InvokeAsync(string operation, JsonObject args, CallOptions? options, CancellationToken cancellationToken)");
            w.line("{");
            w.indent();
            w.line("switch (operation)");
            w.line("{");
            w.indent();
            for (p, info) in self.plan.operations.iter().zip(infos) {
                let ty = request_type(p.resource, info);
                w.line(format!("case {}:", lit(&p.op.id.0)));
                w.line("{");
                w.indent();
                decode(&mut w, &ty);
                w.line("{");
                w.line(format!(
                    "    return await Core.CallAsync(Ops.{}, args, options, cancellationToken);",
                    info.field
                ));
                w.line("}");
                w.line(format!(
                    "return Typed.Untyped(await {}.{}Async(request, options, cancellationToken));",
                    paths[p.resource], info.member
                ));
                w.dedent();
                w.line("}");
            }
            w.line("default:");
            w.line("    return Typed.UnknownOperation<JsonNode?>(operation);");
            w.dedent();
            w.line("}");
            w.dedent();
            w.line("}");
            // PreviewOperationAsync
            w.blank();
            w.line("async Task<Result<PreviewResult>> IDispatch.PreviewOperationAsync(string operation, JsonObject args, CallOptions? options, CancellationToken cancellationToken)");
            w.line("{");
            w.indent();
            w.line("switch (operation)");
            w.line("{");
            w.indent();
            for (p, info) in self.plan.operations.iter().zip(infos) {
                w.line(format!("case {}:", lit(&p.op.id.0)));
                match &info.preview {
                    Some(preview) => {
                        let ty = request_type(p.resource, info);
                        w.line("{");
                        w.indent();
                        decode(&mut w, &ty);
                        w.line("{");
                        w.line(format!(
                        "    return await Core.PreviewAsync(Ops.{}, args, options, cancellationToken);",
                        info.field
                    ));
                        w.line("}");
                        w.line(format!(
                            "return await {}.{preview}Async(request, options, cancellationToken);",
                            paths[p.resource]
                        ));
                        w.dedent();
                        w.line("}");
                    }
                    None => {
                        w.line(format!(
                        "    return await Core.PreviewAsync(Ops.{}, args, options, cancellationToken);",
                        info.field
                    ));
                    }
                }
            }
            w.line("default:");
            w.line("    return Typed.UnknownOperation<PreviewResult>(operation);");
            w.dedent();
            w.line("}");
            w.dedent();
            w.line("}");
        }
        // PaginateAsync
        w.blank();
        w.line("IAsyncEnumerable<Result<Page<JsonNode?>>> IDispatch.PaginateAsync(string operation, JsonObject args, CallOptions? options, CancellationToken cancellationToken)");
        w.line("{");
        w.indent();
        w.line("switch (operation)");
        w.line("{");
        w.indent();
        for (p, info) in self.plan.operations.iter().zip(infos) {
            let Some(pages) = &info.pages else {
                continue;
            };
            let ty = request_type(p.resource, info);
            w.line(format!("case {}:", lit(&p.op.id.0)));
            w.line("{");
            w.indent();
            decode(&mut w, &ty);
            w.line("{");
            w.line(format!(
                "    return Core.PagesAsync(Ops.{}, args, options, cancellationToken);",
                info.field
            ));
            w.line("}");
            w.line(format!(
                "return Typed.UntypedPagesAsync({}.{pages}Async(request, options, cancellationToken), cancellationToken);",
                paths[p.resource]
            ));
            w.dedent();
            w.line("}");
        }
        w.line("default:");
        w.indent();
        w.line("return Typed.Once(DispatchOperations.Any(op => op.Id == operation)");
        w.line("    ? Typed.NotPaginated<Page<JsonNode?>>(operation)");
        w.line("    : Typed.UnknownOperation<Page<JsonNode?>>(operation));");
        w.dedent();
        w.dedent();
        w.line("}");
        w.dedent();
        w.line("}");
        // StreamEvents
        w.blank();
        w.line("EventStream<JsonNode?>? IDispatch.StreamEvents(string operation, JsonObject args, CallOptions? options)");
        w.line("{");
        w.indent();
        w.line("switch (operation)");
        w.line("{");
        w.indent();
        for (p, info) in self.plan.operations.iter().zip(infos) {
            let Some(stream) = &info.stream else {
                continue;
            };
            let ty = request_type(p.resource, info);
            w.line(format!("case {}:", lit(&p.op.id.0)));
            w.line("{");
            w.indent();
            decode(&mut w, &ty);
            w.line("{");
            w.line(format!(
                "    return Core.Stream(Ops.{}, args, options);",
                info.field
            ));
            w.line("}");
            w.line(format!(
                "return {}.{stream}Async(request, options).Untyped();",
                paths[p.resource]
            ));
            w.dedent();
            w.line("}");
        }
        w.line("default:");
        w.line("    return null;");
        w.dedent();
        w.line("}");
        w.dedent();
        w.line("}");
        // Macros
        let macros_class = self.macros_class();
        for (preview, ret, run) in [
            (false, "JsonNode?", "RunMacroAsync"),
            (true, "PreviewResult", "PreviewMacroAsync"),
        ] {
            w.blank();
            if self.plan.macros.is_empty() {
                w.line(format!(
                    "Task<Result<{ret}>> IDispatch.{run}(string name, JsonObject input, CallOptions? options, CancellationToken cancellationToken) =>"
                ));
                w.line(format!(
                    "    Task.FromResult(Typed.UnknownMacro<{ret}>(name));"
                ));
                continue;
            }
            w.line(format!(
                "async Task<Result<{ret}>> IDispatch.{run}(string name, JsonObject input, CallOptions? options, CancellationToken cancellationToken)"
            ));
            w.line("{");
            w.indent();
            w.line("switch (name)");
            w.line("{");
            w.indent();
            for (k, m) in self.plan.macros.iter().enumerate() {
                let member = &self.names.macros[k].member;
                let ty = format!("{macros_class}.{member}Input");
                w.line(format!("case {}:", lit(m.name())));
                w.line("{");
                w.indent();
                w.line(format!(
                    "if (!Typed.TryDecodeArgs<{ty}>(input, {ty}.FromJson, out var typed))"
                ));
                w.line("{");
                w.line(format!(
                    "    return await Core.{run}(Ops.Macro{member}, input, options, cancellationToken);"
                ));
                w.line("}");
                let method = if preview {
                    format!("Preview{member}Async")
                } else {
                    format!("{member}Async")
                };
                w.line(format!(
                    "return await Macros.{method}(typed, options, cancellationToken);"
                ));
                w.dedent();
                w.line("}");
            }
            w.line("default:");
            w.line(format!("    return Typed.UnknownMacro<{ret}>(name);"));
            w.dedent();
            w.line("}");
            w.dedent();
            w.line("}");
        }
        w.dedent();
        w.line("}");
        w.finish()
    }
}

/// `{ a, b }`, or `{ }` without items, as `dotnet format` spaces them.
fn array_literal(items: &str) -> String {
    if items.is_empty() {
        "{ }".into()
    } else {
        format!("{{ {items} }}")
    }
}
