//! Browser ESM package with explicit, scoped registration.

use serde_json::{Value, json};
use tungsten_emit::{CommentStyle, header};
use tungsten_ir::Ir;

use crate::Options;

pub(crate) fn json_text(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(value).unwrap_or_default();
    text.push('\n');
    text
}

pub(crate) fn package_json(options: &Options) -> String {
    let mut dependencies = serde_json::Map::new();
    let mut entries = vec![
        ("@elysra/tungsten-runtime".to_string(), options.sdk_runtime.clone()),
        ("@elysra/tungsten-webmcp".to_string(), options.runtime.clone()),
        (
            "zod".to_string(),
            tungsten_emit_ts::options::ZOD_RANGE.into(),
        ),
        (options.sdk_package.clone(), options.sdk.clone()),
    ];
    entries.sort();
    entries.dedup_by(|a, b| a.0 == b.0);
    for (name, specifier) in entries {
        dependencies.insert(name, json!(specifier));
    }
    json_text(&json!({
        "name": options.package,
        "version": options.version,
        "description": "Browser WebMCP adapter generated by tungsten.",
        "type": "module",
        "sideEffects": false,
        "types": "./dist/index.d.ts",
        "exports": {
            ".": { "types": "./dist/index.d.ts", "import": "./dist/index.js" },
            "./manifest.json": "./manifest.json",
            "./catalog": { "types": "./dist/catalog.d.ts", "import": "./dist/catalog.js" },
            "./groups/*": { "types": "./dist/groups/*/index.d.ts", "import": "./dist/groups/*/index.js" },
        },
        "files": ["dist", "manifest.json"],
        "scripts": {
            "build": "tsc -p tsconfig.json",
            "typecheck": "tsc -p tsconfig.json --noEmit",
        },
        "dependencies": dependencies,
        "devDependencies": { "typescript": "5.9.3" },
    }))
}

