use crate::options::{DEFAULT_RANGE, NODE_TYPES_VERSION, Options, TYPESCRIPT_VERSION};

/// JSON with two-space indent and a final newline.
fn json_text(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(value).unwrap_or_default();
    text.push('\n');
    text
}

/// A TypeScript string literal.
fn ts_string(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_default()
}

pub(crate) fn package_json(ir: &Ir, opts: &Options) -> String {
    let mut deps = Map::new();
    let mut entries = vec![
        ("@tungsten/mcp".to_string(), opts.runtime.clone()),
        ("@tungsten/runtime".to_string(), DEFAULT_RANGE.to_string()),
        (opts.sdk_package.clone(), opts.sdk.clone()),
    ];
    entries.sort();
    entries.dedup_by(|a, b| a.0 == b.0);
    for (name, spec) in entries {
        deps.insert(name, json!(spec));
    }
    let mut bin = Map::new();
    bin.insert(opts.bin.clone(), json!("./dist/server.js"));
    json_text(&json!({
        "name": opts.package,
        "version": opts.version,
        "description": format!("MCP server for the {} API, generated by tungsten.", title(ir)),
        "type": "module",
        "bin": bin,
        "files": ["dist", "manifest.json"],
        "engines": { "node": ">=22" },
        "scripts": {
            "build": "tsc -p tsconfig.json",
            "typecheck": "tsc -p tsconfig.json --noEmit",
            "start": "node dist/server.js",
        },
        "dependencies": deps,
        "devDependencies": {
            "@types/node": NODE_TYPES_VERSION,
            "typescript": TYPESCRIPT_VERSION,
        },
    }))
}

